n = int(input("Введите количество чисел: "))

count = 0 # количество отрицательных чисел
total = 0 # сумма отрицательных чисел

for i in range(n):
    number = int(input("Введите число: "))
    if number < 0:
        count = count + 1 # увеличиваем количество отрицательных
        total = total + number # добавляем отрицательное число к сумме

print()
print("Количество отрицательных:", count)
print("Сумма отрицательных:", total)