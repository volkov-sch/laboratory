from table import column_sums, diagonal_pattern, row_sums, transform  # подключаю обработку таблиц


def read_row(columns):  # ввожу строку нужной длины
    while True:  # повторяю ввод до правильного количества чисел
        row = []  # создаю новую строку
        for part in input("Строка таблицы: ").split():  # перебираю введённые части
            row.append(int(part))  # добавляю целые числа
        if len(row) == columns:  # проверяю количество столбцов
            return row  # возвращаю подходящую строку
        print("Нужно ровно", columns, "чисел")  # объясняю причину повторного ввода


def print_matrix(matrix):  # вывожу таблицу по строкам
    for row in matrix:  # перебираю строки
        print(*row)  # передаю элементы строки в print отдельными аргументами


def main():  # собираю ввод и вывод заданий
    rows = int(input("Количество строк: "))  # ввожу высоту таблицы
    while rows <= 0:  # размеры должны быть положительными
        rows = int(input("Введите количество строк больше нуля: "))
    columns = int(input("Количество столбцов: "))  # ввожу ширину таблицы
    while columns <= 0:  # проверяю ширину
        columns = int(input("Введите количество столбцов больше нуля: "))
    matrix = []  # создаю исходную таблицу
    for i in range(rows):  # ввожу нужное количество строк
        matrix.append(read_row(columns))  # каждая строка создаётся отдельно

    print("Суммы строк:", row_sums(matrix))  # вывожу суммы строк
    print("Суммы столбцов:", column_sums(matrix))  # вывожу суммы столбцов
    result = transform(matrix)  # получаю результат индивидуального варианта
    print("Исходная таблица:")  # показываю сохранность исходных данных
    print_matrix(matrix)  # вывожу исходную таблицу
    print("Новая таблица:")  # вывожу заголовок результата
    print_matrix(result)  # вывожу преобразованную таблицу

    size = int(input("Положительный размер узора: "))  # ввожу размер квадратной таблицы
    while size <= 0:  # повторяю ввод для неположительного размера
        size = int(input("Введите размер больше нуля: "))
    print("Диагональный узор:")  # вывожу заголовок
    print_matrix(diagonal_pattern(size))  # создаю и вывожу узор


if __name__ == "__main__":  # диалог не запускается при импорте
    main()  # запускаю программу
